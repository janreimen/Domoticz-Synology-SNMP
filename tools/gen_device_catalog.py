#!/usr/bin/env python3
"""Generate docs/DEVICES.md: the devices the plugin creates, taken from the simulated NAS fixtures.

    python3 tools/gen_device_catalog.py            # (re)write docs/DEVICES.md
    python3 tools/gen_device_catalog.py --check    # exit 1 if the file is out of date (used by the tests)

The fixtures live in tests/ (a DS920+ with four bays and two NVMe cache drives, and a two-bay DS218+),
so the catalogue shows what a typical run produces, not a hand-written promise.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [ROOT, os.path.join(ROOT, "tests")]

import mibdata  # noqa: E402
from helpers import make  # noqa: E402

OUT = os.path.join(ROOT, "docs", "DEVICES.md")
LEVEL_NAMES = {1: "Basic", 2: "Standard", 3: "Full"}
KIND_NAMES = {"temperature": "Temperature", "percentage": "Percentage", "text": "Text",
              "alert": "Alert", "custom": "Custom sensor"}
RATE_HINT = "(rate: first value after the second poll)"


def readings_at(builder, level):
    engine, _, _ = make(builder(), level=level)
    result = engine.cycle()
    return result.info, {r.key: r for r in result.readings}


def catalogue(builder):
    """Return (info, {key: (min_level, Reading)}) for one fixture."""
    info, full = readings_at(builder, 3)
    first = {}
    for level in (1, 2, 3):
        _, got = readings_at(builder, level)
        for key in got:
            first.setdefault(key, level)
    return info, {k: (first[k], r) for k, r in full.items()}


def example(r):
    if r.pending:
        return RATE_HINT
    if r.kind == "alert":
        return "%s (level %d)" % (r.svalue, r.nvalue)
    if r.kind == "custom":
        return ("%s %s" % (r.svalue, r.unit)).strip()
    if r.kind == "temperature":
        return "%s C" % r.svalue
    if r.kind == "percentage":
        return "%s %%" % r.svalue
    return r.svalue


def esc(text):
    return text.replace("|", "\\|").replace("\n", " ")


def table(rows):
    lines = ["| Device ID | Name | Type | From level | Visible | Example value |",
             "|---|---|---|---|---|---|"]
    for key, (level, r) in rows:
        lines.append("| `%s` | %s | %s | %s | %s | %s |" % (
            key, esc(r.name), KIND_NAMES.get(r.kind, r.kind), LEVEL_NAMES[level],
            "yes" if r.used else "no", esc(example(r))))
    return lines


def natural(key):
    return [int(p) if p.isdigit() else p for p in re.split(r"(\d+)", key)]


def render():
    out = [
        "# Devices",
        "",
        "<!-- generated by tools/gen_device_catalog.py - do not edit by hand -->",
        "",
        "This is what the plugin creates for two simulated NAS models. The list is **not fixed**: drives, volumes, pools,",
        "network ports, UPS, expansion units, SSD cache and GPU are detected on the NAS, so your NAS gets exactly the",
        "devices that match its hardware (a five-bay DS1525 gets five drives, the two-bay DS218+ below two).",
        "",
        "* **Device ID** is the stable key the plugin matches on (shown in *Setup > Devices* as *IDX* / hardware ID, and in",
        "  the debug log). Do not rename it; names, visibility and history of a device are never overwritten by the plugin.",
        "* **From level** is the lowest *Detail level* that creates the device (Basic < Standard < Full).",
        "* **Visible** is whether the device is shown in Domoticz by default; devices marked *no* exist but are not in the",
        "  *Used* list. Add them under *Setup > Devices*.",
        "* Alert levels: 0 grey (n/a), 1 green (OK), 2 yellow (warning/busy), 3 orange (degraded), 4 red (critical).",
        "* Rates (network Mbit/s, drive MB/s) need two samples: their devices are created by the second poll,",
        "  one poll interval after the start. So a first poll creates fewer devices than the totals below.",
        "",
    ]
    for title, builder in (("Synology DS920+ (4 bays + 2 NVMe cache, DSM 7)", mibdata.ds920),
                           ("Synology DS218+ (2 bays, DSM 6)", mibdata.ds218)):
        info, cat = catalogue(builder)
        rows = sorted(cat.items(), key=lambda kv: (kv[1][0], natural(kv[0])))
        visible = sum(1 for _, (_, r) in rows if r.used)
        out += ["## %s" % title, "",
                "%d devices at *Full*, %d of them visible by default. Model reported by the NAS: `%s`, DSM `%s`." % (
                    len(rows), visible, info.get("model", "?"), info.get("version", "?")),
                ""]
        out += table(rows)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if docs/DEVICES.md is not up to date")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        try:
            with open(OUT, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            sys.stderr.write("docs/DEVICES.md is out of date: run python3 tools/gen_device_catalog.py\n")
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(OUT, ROOT), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
